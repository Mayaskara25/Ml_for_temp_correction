def mae_rmse(y_true_c, y_pred_c):
    err = np.asarray(y_pred_c) - np.asarray(y_true_c)
    mae = float(np.mean(np.abs(err)))
    rmse = float(np.sqrt(np.mean(err ** 2)))
    return mae, rmse


def write_header(tflite_bytes, out_path, array_name):
    hex_parts = []
    for i, b in enumerate(tflite_bytes):
        if i % 12 == 0:
            hex_parts.append("\n  ")
        hex_parts.append(f"0x{b:02x}, ")
    guard = os.path.splitext(os.path.basename(out_path))[0].upper() + '_H'
    header = f"""\
// Auto-generated by train_multimodel_v2.py — do not edit manually.
#ifndef {guard}
#define {guard}

alignas(8) const unsigned char {array_name}[] = {{{''.join(hex_parts)}
}};
const unsigned int {array_name}_len = {len(tflite_bytes)};

#endif // {guard}
"""
    with open(out_path, 'w') as f:
        f.write(header)
    print(f"  Wrote {out_path} ({len(tflite_bytes)} bytes)")


def record_result(model_name, precision, tflite_bytes, pred_c, pt_true_c, param_count):
    mae, rmse = mae_rmse(pt_true_c, pred_c)
    RESULTS.append(dict(
        model_name=model_name, precision=precision,
        val_MAE_C=round(mae, 4), val_RMSE_C=round(rmse, 4),
        size_bytes=len(tflite_bytes), param_count=param_count
    ))
    print(f"  {model_name} [{precision}] -- val MAE: {mae:.4f} C, RMSE: {rmse:.4f} C, size: {len(tflite_bytes)} bytes")


def convert_float32(model):
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    return converter.convert()


def convert_ptq_int8(model, rep_data_fn):
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = rep_data_fn
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    return converter.convert()


def convert_qat_int8(model, X_train_qat, y_train_qat, rep_data_fn, custom_objects=None, epochs=QAT_EPOCHS):
    if custom_objects:
        with tfmot.quantization.keras.quantize_scope(custom_objects):
            qat_model = tfmot.quantization.keras.quantize_model(model)
    else:
        qat_model = tfmot.quantization.keras.quantize_model(model)
    qat_model.compile(optimizer='adam', loss='mse')
    qat_model.fit(X_train_qat, y_train_qat, epochs=epochs, batch_size=64, verbose=1)

    converter = tf.lite.TFLiteConverter.from_keras_model(qat_model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = rep_data_fn
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    return converter.convert()


def run_tflite_single_input(tflite_bytes, X_val, is_int8=True):
    interpreter = tf.lite.Interpreter(model_content=tflite_bytes)
    interpreter.allocate_tensors()
    in_detail = interpreter.get_input_details()[0]
    out_detail = interpreter.get_output_details()[0]

    n = X_val.shape[0]
    preds = np.zeros(n, dtype=np.float32)
    for i in range(n):
        sample = X_val[i:i + 1]
        if is_int8:
            scale, zp = in_detail['quantization']
            sample_q = np.round(sample / scale + zp).astype(in_detail['dtype'])
            interpreter.set_tensor(in_detail['index'], sample_q)
        else:
            interpreter.set_tensor(in_detail['index'], sample.astype(in_detail['dtype']))
        interpreter.invoke()
        out = interpreter.get_tensor(out_detail['index'])
        if is_int8:
            scale, zp = out_detail['quantization']
            out = (out.astype(np.float32) - zp) * scale
        preds[i] = out.flatten()[0]
    return preds


def run_tflite_multi_input(tflite_bytes, X_seq_val, X_had_val, is_int8=True):
    interpreter = tf.lite.Interpreter(model_content=tflite_bytes)
    interpreter.allocate_tensors()
    input_details = interpreter.get_input_details()
    out_detail = interpreter.get_output_details()[0]

    # Identify the 3D (sequence) vs 2D (Hadamard) input tensors by shape rank
    # rather than by name -- robust to any name-mangling the converter applies.
    seq_detail = next(d for d in input_details if len(d['shape']) == 3)
    had_detail = next(d for d in input_details if len(d['shape']) == 2)

    n = X_seq_val.shape[0]
    preds = np.zeros(n, dtype=np.float32)
    for i in range(n):
        seq_sample = X_seq_val[i:i + 1]
        had_sample = X_had_val[i:i + 1]
        if is_int8:
            s_scale, s_zp = seq_detail['quantization']
            interpreter.set_tensor(seq_detail['index'], np.round(seq_sample / s_scale + s_zp).astype(seq_detail['dtype']))
            h_scale, h_zp = had_detail['quantization']
            interpreter.set_tensor(had_detail['index'], np.round(had_sample / h_scale + h_zp).astype(had_detail['dtype']))
        else:
            interpreter.set_tensor(seq_detail['index'], seq_sample.astype(seq_detail['dtype']))
            interpreter.set_tensor(had_detail['index'], had_sample.astype(had_detail['dtype']))
        interpreter.invoke()
        out = interpreter.get_tensor(out_detail['index'])
        if is_int8:
            o_scale, o_zp = out_detail['quantization']
            out = (out.astype(np.float32) - o_zp) * o_scale
        preds[i] = out.flatten()[0]
    return preds


