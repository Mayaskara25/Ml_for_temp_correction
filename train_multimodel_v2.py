KALMAN_Q_TEMP = 0.001
KALMAN_Q_VEL = 0.0001
KALMAN_R_MEAS = 0.25


def kalman_filter_python(measurements, dt):
    """Mirrors the exact predict/update equations in kalman_filter_v2.h."""
    n = len(measurements)
    preds = np.zeros(n)
    x = measurements[0]
    v = 0.0
    p00, p01, p10, p11 = 1.0, 0.0, 0.0, 1.0
    preds[0] = x
    for i in range(1, n):
        z = measurements[i]
        x_pred = x + v * dt
        v_pred = v

        p00_pred = p00 + dt * (p10 + p01) + dt * dt * p11 + KALMAN_Q_TEMP
        p01_pred = p01 + dt * p11
        p10_pred = p10 + dt * p11
        p11_pred = p11 + KALMAN_Q_VEL

        innovation = z - x_pred
        S = p00_pred + KALMAN_R_MEAS
        k0 = p00_pred / S
        k1 = p10_pred / S

        x = x_pred + k0 * innovation
        v = v_pred + k1 * innovation

        p00 = (1 - k0) * p00_pred
        p01 = (1 - k0) * p01_pred
        p10 = p10_pred - k1 * p00_pred
        p11 = p11_pred - k1 * p01_pred

        preds[i] = x
    return preds


