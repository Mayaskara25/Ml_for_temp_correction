def lag_model_mse(tau, rate_vals, k_vals, pt_vals):
    physics_est = k_vals + tau * rate_vals
    return np.mean((physics_est - pt_vals) ** 2)


def causal_moving_average(x, window):
    """Past-only moving average (no future lookahead) -- realizable on the firmware."""
    result = np.zeros_like(x)
    for i in range(len(x)):
        start = max(0, i - window + 1)
        result[i] = np.mean(x[start:i + 1])
    return result


