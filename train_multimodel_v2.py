"""
train_multimodel_v2.py
------------------------
Trains and compares 5 correction approaches against the real dataset.csv:
  1. Dense_v2            -- 20-input Dense MLP (K-type window + derivative window)
  2. TCN_Hadamard_v2      -- dilated causal Conv1D branch + Hadamard-transform branch
  3. Hybrid_Physics_v2    -- fitted first-order lag physics model + residual Dense net
  4. RandomForest         -- sklearn RF exported to C via emlearn
  5. Kalman               -- hand-written constant-velocity Kalman filter (kalman_filter_v2.h)

CLI: python train_multimodel_v2.py --csv dataset.csv

Known environment quirks handled here (discovered while building this script):
  - TF 2.21 defaults to Keras 3, but tensorflow-model-optimization's
    quantize_model() targets legacy Keras 2. TF_USE_LEGACY_KERAS=1 (set before
    importing tensorflow) makes tf.keras bind to the tf_keras compat package,
    which resolves this for plain Dense models.
  - tfmot's default quantize registry does NOT support Conv1D layers at all,
    independent of the Keras-3 issue above. QAT for TCN_Hadamard_v2 will
    therefore fail -- this is caught, logged clearly, and skipped; only
    float32 + ptq_int8 are produced for that model.
  - TFLite's int8 calibrator has a bug with multi-input models when the
    representative_dataset yields positional lists -- it must yield a dict
    keyed by the Keras Input layer's `name`.
  - emlearn's default dtype='int16_t' truncates raw feature/threshold values
    to integers, destroying sub-degree precision for this data. We use
    dtype='float' instead so on-device RF behavior matches the sklearn
    predictions used for the comparison table.
"""

